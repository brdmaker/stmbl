#!/usr/bin/env python
import re
import sys
import os

config = []

# findline() in shared/hal.c looks at most 64 chars ahead for '\n'; a longer
# line makes hal_parse() silently stop, dropping the rest of the template.
MAX_LINE = 63

errors = 0
for infile in sys.argv[2:]:
    with open(infile) as f:
        content = f.read()
    for n, line in enumerate(content.splitlines(), 1):
        if len(line) > MAX_LINE:
            sys.stderr.write("%s:%d: line is %d chars, max %d (hal_parse would stop here)\n" % (infile, n, len(line), MAX_LINE))
            errors += 1
    config.append((os.path.splitext(os.path.basename(infile))[0], content))
if errors:
    sys.exit(1)

code = open(sys.argv[1], 'w')

code.write("//generated by " + sys.argv[0] + " DO NOT EDIT\n\n")
code.write("#include \"config.h\"\n\n")
code.write("const uint32_t num_of_config_templates = " + str(len(config)) + ";\n\n")

code.write("config_template_t config_templates[] = {\n")

for index, (file_name, content) in enumerate(config):
    code.write("{\n")
    code.write(".name = \"" + file_name + "\",\n")
    code.write(".config = \"\\\n")
    for line in content.splitlines():
        code.write(line + "\\n\\\n")
    code.write("\"\n},\n\n")
code.write("};\n")

code.close()
