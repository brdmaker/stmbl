#!/usr/bin/env python3
"""The HAL components' reference, generated from their sources into
docs/components/: one page per component and an index.

A page holds the component's description (its first comment before the
first pin that isn't the licence: a /* */ or /** */ block or a run of //
lines), its pins with their trailing comments, and the config templates
(conf/template/*.txt) that load it or link its pins. Documenting a
component is editing its source; this writes the pages:

    tools/comp_docs.py            write docs/components/
    tools/comp_docs.py --check    fail if the pages aren't current (make -C host check)
"""
import glob
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "docs", "components")
SOURCES = [  # (glob, target, page prefix)
    ("shared/comps/*.c", "F4 and F3 (shared)", ""),
    ("src/comps/*.c", "F4 (logic board)", ""),
    ("src/comps/hw/*.c", "F4 (logic board, board io)", "f4-"),
    ("stm32f303/src/comps/*.c", "F3 (HV board)", "f3-"),
]
LICENCE = ("This program is free software", "Copyright (C)")


def parse(text):
    """(name, description, pins[(name, count, comment)]) of a component source."""
    m = re.search(r"^\s*HAL_COMP\((\w+)\)\s*;", text, re.M)
    if not m:
        return None
    name = m.group(1)
    first_pin = re.search(r"^\s*HAL_PINA?\(", text, re.M)
    head = text[: first_pin.start()] if first_pin else text
    desc = ""
    for c in re.finditer(r"/\*\*?(.*?)\*/|((?:^[ \t]*//[^\n]*\n)+)", head, re.S | re.M):
        body = c.group(1) if c.group(1) is not None else c.group(2)
        if any(l in body for l in LICENCE):
            continue
        lines = [re.sub(r"^\s*(\*+|//+)\s?", "", l).rstrip() for l in body.splitlines()]
        desc = "\n".join(lines).strip()
        if desc:
            break
    pins = []
    for p in re.finditer(r"^\s*HAL_PIN(A)?\((\w+)(?:,\s*(\d+))?\)\s*;[ \t]*(?://\s*(.*))?$", text, re.M):
        pins.append((p.group(2), int(p.group(3)) if p.group(1) else 1, (p.group(4) or "").strip()))
    return name, desc, pins


def templates_using(name):
    used = []
    for t in sorted(glob.glob(os.path.join(ROOT, "conf", "template", "*.txt"))):
        s = open(t).read()
        if re.search(r"^\s*load\s+%s\b" % name, s, re.M) or re.search(r"\b%s\d+\.\w+" % name, s):
            used.append(os.path.splitext(os.path.basename(t))[0])
    return used


def md_escape(s):
    return s.replace("|", "\\|")


def as_markdown(desc):
    """indented lines (pin lists, formulas in the comment) as code blocks"""
    out, block = [], []
    for l in desc.split("\n") + [""]:
        if l.startswith("  ") and l.strip():
            block.append(l)
            continue
        if block:
            out += ["```"] + block + ["```"]
            block = []
        out.append(l)
    return "\n".join(out).rstrip()


def page(name, rel, target, desc, pins):
    comp = name.split(" ")[0]
    out = ["# %s" % name, "", "*%s, `%s`*" % (target, rel), ""]
    out += [as_markdown(desc) if desc else "*(no description in the source yet: a comment before its pins)*", ""]
    used = templates_using(comp)
    if used:
        out += ["**Config templates:** " + ", ".join("`%s`" % u for u in used), ""]
    documented = sum(1 for p in pins if p[2])
    out += ["## Pins (%d, %d described)" % (len(pins), documented), ""]
    if pins:
        out += ["| pin | description |", "|---|---|"]
        for pn, count, comment in pins:
            label = "`%s0`..`%s%d`" % (pn, pn, count - 1) if count > 1 else "`%s`" % pn
            out.append("| %s | %s |" % (label, md_escape(comment)))
        out.append("")
    out += ["*Generated by `tools/comp_docs.py` from the source; edit the source, not this page.*", ""]
    return "\n".join(out)


def generate():
    pages, index = {}, []
    for pattern, target, prefix in SOURCES:
        for path in sorted(glob.glob(os.path.join(ROOT, pattern))):
            r = parse(open(path, errors="replace").read())
            if not r:
                continue
            name, desc, pins = r
            rel = os.path.relpath(path, ROOT)
            base  = os.path.splitext(os.path.basename(path))[0]
            fname = prefix + base + ".md"  # the file's name: variants (uf2.c, io4.c) share a component name
            pages[fname] = page(name if base == name else "%s (%s.c)" % (name, base), rel, target, desc, pins)
            summary = desc.split("\n\n")[0].replace("\n", " ") if desc else ""
            if len(summary) > 140:
                summary = summary[:137].rsplit(" ", 1)[0] + " ..."
            documented = sum(1 for p in pins if p[2])
            index.append((target, name if base == name else base, fname, summary, documented, len(pins)))
    lines = ["# Component reference", "",
             "Every HAL component of the firmware, generated from its source by `tools/comp_docs.py` "
             "(`make -C host check` fails while a page is out of date). Describe a component in a comment "
             "before its pins and each pin in a comment after it; then run `tools/comp_docs.py`.", ""]
    total_d = sum(i[4] for i in index)
    total_p = sum(i[5] for i in index)
    lines += ["%d components, %d of %d pins described." % (len(index), total_d, total_p), ""]
    for target in [s[1] for s in SOURCES]:
        rows = [i for i in index if i[0] == target]
        if not rows:
            continue
        lines += ["## " + target, "", "| component | pins described | summary |", "|---|---|---|"]
        for _, name, fname, summary, d, n in rows:
            lines.append("| [%s](%s) | %d/%d | %s |" % (name, fname, d, n, md_escape(summary)))
        lines.append("")
    pages["README.md"] = "\n".join(lines)
    return pages


def main():
    check = "--check" in sys.argv
    pages = generate()
    stale = []
    for fname, text in pages.items():
        path = os.path.join(OUT, fname)
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(fname)
            if not check:
                os.makedirs(OUT, exist_ok=True)
                open(path, "w").write(text)
    extra = [os.path.basename(p) for p in glob.glob(os.path.join(OUT, "*.md")) if os.path.basename(p) not in pages]
    if check:
        if stale or extra:
            print("not ok - docs/components is out of date (%s): run tools/comp_docs.py"
                  % ", ".join((stale + extra)[:8]))
            sys.exit(1)
        print("ok - docs/components is current (%d pages)" % len(pages))
        return
    for e in extra:
        os.remove(os.path.join(OUT, e))
    print("docs/components: %d pages, %d written, %d removed" % (len(pages), len(stale), len(extra)))


if __name__ == "__main__":
    main()
