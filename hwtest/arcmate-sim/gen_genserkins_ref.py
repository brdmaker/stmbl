#!/usr/bin/env python3
"""Reference poses from LinuxCNC's genserkins for host/tests/robot: a
headless display that jogs the simulated ARC Mate's joints to a set of
poses and records LinuxCNC's joint feedback with the Cartesian pose
genserkins computes from it (X Y Z [mm], A B C [deg]).

    make genserkins-ref     (writes ../../host/tests/robot/genserkins_ref.txt)
"""
import os
import time

import hal
import linuxcnc

S = linuxcnc.stat()
C = linuxcnc.command()
E = linuxcnc.error_channel()
OUT = os.environ.get("GENSER_OUT", "genserkins_ref.txt")
# joint increments [deg] from the home pose, one set per sample (J5 is at
# -90 at home; its range is -130..130)
POSES = [(0, 0, 0, 0, 0, 0), (30, 10, -20, 40, 30, -60), (-45, 25, 15, -80, -40, 120),
         (90, -20, 40, 10, 60, 30), (-120, 15, -30, 150, -35, -150), (10, 40, 60, -30, 20, 200),
         (60, -10, -50, 90, 45, 10), (-20, 30, 20, 0, -30, -90)]


def poll():
    S.poll()
    return S


def wait(pred, t):
    end = time.time() + t
    while time.time() < end:
        if pred(poll()):
            return True
        time.sleep(0.01)
    return False


def main():
    h = hal.component("genser_ref")
    h.ready()
    wait(lambda s: s.task_state != 0, 20)
    C.state(linuxcnc.STATE_ESTOP_RESET)
    C.state(linuxcnc.STATE_ON)
    wait(lambda s: s.task_state == linuxcnc.STATE_ON, 5)
    time.sleep(0.5)
    C.mode(linuxcnc.MODE_MANUAL)
    C.wait_complete()
    C.home(-1)
    wait(lambda s: all(s.homed[j] for j in range(6)), 10)
    C.teleop_enable(0)
    C.wait_complete()
    home = list(poll().joint_actual_position[:6])
    rows = []
    notes = []
    for inc in POSES:
        for j in range(6):  # one joint at a time
            target = home[j] + inc[j]
            d = target - poll().joint_actual_position[j]
            if abs(d) > 1e-6:
                C.jog(linuxcnc.JOG_INCREMENT, 1, j, 30.0, d)
                time.sleep(0.1)
                wait(lambda s: s.inpos and abs(s.joint[j]["velocity"]) < 1e-9, 30)
        time.sleep(0.5)
        s = poll()
        if s.task_state != linuxcnc.STATE_ON:
            notes.append("# machine not on (state %d) after %s" % (s.task_state, inc))
        while True:
            e = E.poll()
            if not e:
                break
            notes.append("# error: %s" % (e[1],))
        rows.append("pair " + " ".join("%.9f" % v for v in list(s.joint_actual_position[:6]) +
                                       list(s.actual_position[:6])))
    C.state(linuxcnc.STATE_OFF)
    with open(OUT, "w") as f:
        f.write("# GENERATED by hwtest/arcmate-sim/gen_genserkins_ref.py: LinuxCNC %s genserkins\n"
                % linuxcnc.version)
        f.write("# pair: joints (DH theta) [deg], X Y Z [mm], A B C [deg]; DH of arcmate.arm\n")
        f.write("\n".join(rows) + "\n")
    with open(OUT + ".log", "w") as f:
        f.write("\n".join(notes) + "\n")


if __name__ == "__main__":
    main()
