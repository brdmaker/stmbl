// node tools/gen_arm_demo.js: js/arm_demo.js, the simulated arm's model files (the ARC Mate with its tool changer,
// as hwtest/arcmate-sim and linuxcnc/vis3d have them), for the console's simulation (no server to ask)
"use strict";
const fs = require("fs"), path = require("path");
const ROOT = path.resolve(__dirname, "../../..");
const model = path.join(ROOT, "linuxcnc/vis3d/models/arm6_changer.vis"), root = path.dirname(model);
const files = {}, rel = (p) => path.relative(root, p).split(path.sep).join("/");
function add(p) {
  const name = rel(p); if (name in files) return;
  const text = fs.readFileSync(p, "utf8"); files[name] = text;
  for (const line of text.split("\n")) {
    const w = line.split("#")[0].trim().split(/\s+/);
    if (w[0] === "include") { const q = path.resolve(path.dirname(p), w[1]); if (fs.existsSync(q)) add(q); }
  }
}
add(model);
const cell = path.join(ROOT, "hwtest/arcmate-sim/cell_changer.txt"), tools = path.join(ROOT, "host/arm/arcmate/tools.txt");
add(cell); add(tools);
const out = `// GENERATED by tools/gen_arm_demo.js from linuxcnc/vis3d/models/arm6_changer.vis, hwtest/arcmate-sim/cell_changer.txt
// and host/arm/arcmate/tools.txt: the simulated arm's model (the server's arm_model, for the simulation)
"use strict";
const ARM_DEMO = ${JSON.stringify({ files, model: rel(model), cell: rel(cell), tools: rel(tools) }, null, 1)};
`;
fs.writeFileSync(path.join(__dirname, "../js/arm_demo.js"), out);
console.log("js/arm_demo.js:", Object.keys(files).length, "files,", out.length, "bytes");
