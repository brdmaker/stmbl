#!/usr/bin/env python3
"""Large G-code programs in the style CAM systems write, for stress tests.

    python3 bigcode.py KIND LINES OUT.ngc

KIND:
  surface   3D raster finishing of a relief: short G1 moves, coordinates
            modal (no G1 on each line), 4 decimals, as Fusion/HSM post
  adaptive  adaptive clearing at several depths: G2/G3 trochoids and links
  drill     a perforated plate: G83 peck cycles, one hole per line
  loop      a few lines that run a long time: O-word repeat around an engraving
LINES is about how many lines (for loop: how many repeats of 1000 moves).
All in mm, G54, on a 120 x 80 stock with its top at Z0, under 25 mm deep;
tools from test/sim's table (T1, T3, T5).
"""
import math
import sys


def head(w, title, tool, rpm):
    w("%")
    w("(%s)" % title)
    w("(GENERATED BY WEBUI/MILL/TEST/BIGCODE.PY)")
    w("G90 G94 G17 G21 G40 G49 G80")
    w("G54")
    w("T%d M6" % tool)
    w("G43 H%d" % tool)
    w("S%d M3" % rpm)
    w("M8")


def tail(w):
    w("G0 Z30.")
    w("M5")
    w("M9")
    w("G53 G0 Z0.")
    w("M30")
    w("%")


def relief(x, y):
    """A smooth relief on the 120 x 80 stock, Z -12 ... -0.5."""
    d = math.hypot(x - 60, y - 40)
    return -0.5 - 6 * (1 + math.cos(min(d / 38, 1) * math.pi)) / 2 - 2.5 * (1 + math.sin(x / 9) * math.sin(y / 7)) / 2


def surface(w, n):
    head(w, "RELIEF 3D FINISH  T1 BALL  RASTER", 1, 16000)
    # rows x points ~ n: 120 mm rows, points every `step` mm
    rows = max(10, int(math.sqrt(n * 80 / 120)))
    pts = max(10, n // rows)
    so, step = 80.0 / rows, 120.0 / pts
    w("G0 X0. Y0.")
    w("G0 Z5.")
    w("G1 Z%.4f F800." % relief(0, 0))
    w("F3000.")
    first = True
    for r in range(rows + 1):
        y = r * so
        xs = [i * step for i in range(pts + 1)]
        if r % 2:
            xs.reverse()
        for x in xs:
            z = relief(x, y)
            w(("G1 " if first else "") + "X%.4f Y%.4f Z%.4f" % (x, y, z))
            first = False
    tail(w)


def adaptive(w, n):
    head(w, "POCKET ADAPTIVE  T3 D6  0.6 MM OPTIMAL LOAD", 3, 18000)
    count, depth = 0, 0.0
    per = max(1, n // 6)
    while count < n:
        depth -= 4.0
        if depth < -20:
            depth = -4.0
        w("G0 X10. Y10.")
        w("G0 Z2.")
        w("G1 Z%.3f F600." % depth)
        x, y, k = 10.0, 10.0, 0
        while count < n and k < per:
            # a trochoid: half a circle out (R2), half back (R1.7): 0.6 mm on
            w("G3 X%.4f Y%.4f I2. J0. F4800." % (x + 4.0, y))
            w("G3 X%.4f Y%.4f I-1.7 J0." % (x + 0.6, y))
            x += 0.6
            count += 2
            k += 2
            if x > 104:
                x = 10.0
                y += 3.0
                if y > 70:
                    y = 10.0
                w("G1 Z%.3f" % (depth + 1))
                w("G0 X%.4f Y%.4f" % (x, y))
                w("G1 Z%.3f F600." % depth)
                count += 3
        w("G0 Z5.")
    tail(w)


def drill(w, n):
    head(w, "PERFORATED PLATE  T5 D5  G83 PECK", 5, 6000)
    pitch = math.sqrt(116 * 76 / max(n, 1))
    w("G0 X2. Y2.")
    w("G0 Z10.")
    w("G98 G83 X2. Y2. Z-6. R2. Q1.5 F450.")
    count, y, row = 0, 2.0, 0
    while y <= 78 and count < n:
        xs = [2 + i * pitch for i in range(int(116 / pitch) + 1)]
        if row % 2:
            xs.reverse()
        for x in xs:
            w("X%.4f Y%.4f" % (x, y))
            count += 1
            if count >= n:
                break
        y += pitch
        row += 1
    w("G80")
    tail(w)


def loop(w, n):
    head(w, "ENGRAVE LOOP  T3  O-WORD REPEAT", 3, 18000)
    w("G0 X60. Y40.")
    w("G0 Z1.")
    w("G1 Z-0.2 F300.")
    w("o100 repeat [%d]" % n)
    # 1000 moves of a rose curve, as a 4-line body with its own counter
    w("  #1 = 0")
    w("  o101 while [#1 LT 1000]")
    w("    G1 X[60 + 30 * COS[#1 * 0.36 * 4] * COS[#1 * 0.36]] Y[40 + 30 * COS[#1 * 0.36 * 4] * SIN[#1 * 0.36]] F6000")
    w("    #1 = [#1 + 1]")
    w("  o101 endwhile")
    w("o100 endrepeat")
    tail(w)


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    kind, n, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    with open(out, "w") as f:
        buf = []

        def w(s):
            buf.append(s)
            if len(buf) >= 10000:
                f.write("\n".join(buf) + "\n")
                buf.clear()
        {"surface": surface, "adaptive": adaptive, "drill": drill, "loop": loop}[kind](w, n)
        f.write("\n".join(buf) + "\n")


if __name__ == "__main__":
    main()
