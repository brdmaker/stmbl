#!/usr/bin/env python3
"""model_perturbed.arm: the collision detector's model of the simulated
ARC Mate with errors an identification would plausibly leave: link masses
+-10%, centres of mass off by 1-2 cm, inertias +15%, rotor inertias +10%,
friction parameters +-20% (the plant's gearbox friction also has a hard
stick-slip the smooth model cannot follow). Deterministic.

usage: python3 gen_model_perturbed.py   (writes model_perturbed.arm here)
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
rnd = random.Random(1203)
src = open(os.path.join(HERE, "model_exact.arm")).read().splitlines()
out = ["# GENERATED by gen_model_perturbed.py from model_exact.arm: the",
       "# detector's model with identification-sized errors (see the script)."]
for line in src:
    w = line.split()
    if not w or w[0].startswith("#"):
        if not line.startswith("# Collision detector model") and "EXACTLY" not in line \
                and "plant's values" not in line and "from identification" not in line:
            out.append(line)
        continue
    if w[0] == "link":
        j, v = w[1], [float(x) for x in w[2:]]
        v[0] *= 1 + rnd.choice([-1, 1]) * 0.10
        for k in (1, 2, 3):
            v[k] += rnd.choice([-1, 1]) * rnd.uniform(0.01, 0.02)
        for k in (4, 5, 6):
            v[k] *= 1.15
        out.append("link %s " % j + " ".join("%.5g" % x for x in v))
    elif w[0] == "motor":
        v = w[2:]
        v[1] = "%.5g" % (float(v[1]) * 1.10)
        out.append(" ".join(w[:2] + v))
    elif w[0] == "fric":
        j, v = w[1], [float(x) for x in w[2:]]
        v = [x * (1 + rnd.choice([-1, 1]) * 0.20) for x in v]
        out.append("fric %s " % j + " ".join("%.4g" % x for x in v))
    else:
        out.append(line)
open(os.path.join(HERE, "model_perturbed.arm"), "w").write("\n".join(out) + "\n")
print("wrote model_perturbed.arm")
