#!/usr/bin/env python3
"""Reference data for shared/robot (host/tests/robot/test_robot.c) from an
independent implementation, Peter Corke's Robotics Toolbox for Python
(roboticstoolbox-python, modified-DH links, rne / inertia).

A 6-joint arm with arbitrary DH values (Craig's convention, as genserkins),
masses, centres of mass off every axis and full inertia tensors including
products, so every term of the dynamics is exercised. Writes
rtb_ref.txt next to this script; the C test reads it, so the toolbox is
needed only to regenerate it.

usage: python3 gen_robot_ref.py   (needs roboticstoolbox-python, numpy)
"""
import os
import numpy as np
import roboticstoolbox as rtb

rng = np.random.default_rng(1203)
G = 9.81
links = []
dhp = [  # a, alpha, d, theta0 (Craig): an ARC Mate-like layout, values made up
    (0.0, 0.0, 0.45, 0.0),
    (0.15, -np.pi / 2, 0.0, -np.pi / 2),
    (0.60, 0.0, 0.0, 0.0),
    (0.12, -np.pi / 2, 0.65, 0.0),
    (0.0, np.pi / 2, 0.0, 0.0),
    (0.0, -np.pi / 2, 0.10, 0.3),
]
rows = []
for i, (a, al, d, th0) in enumerate(dhp):
    m = [40.0, 25.0, 15.0, 6.0, 3.0, 1.0][i]
    c = rng.uniform(-0.15, 0.15, 3)
    A = rng.normal(size=(3, 3))
    Ic = A @ A.T * m * 0.002 + np.eye(3) * m * 0.004  # SPD, full
    links.append(rtb.RevoluteMDH(a=a, alpha=al, d=d, offset=th0, m=m, r=c, I=Ic,
                                 Jm=0, G=1, B=0, Tc=[0, 0]))
    rows.append("link %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g %.17g" % (
        a, al, d, th0, m, c[0], c[1], c[2], Ic[0, 0], Ic[1, 1], Ic[2, 2], Ic[0, 1], Ic[0, 2], Ic[1, 2]))
bot = rtb.DHRobot(links, gravity=[0, 0, -G])
for k in range(20):
    q = rng.uniform(-np.pi, np.pi, 6)
    qd = rng.uniform(-3, 3, 6)
    qdd = rng.uniform(-10, 10, 6)
    tau = bot.rne(q, qd, qdd)
    rows.append("rne " + " ".join("%.17g" % x for x in np.concatenate([q, qd, qdd, tau])))
for k in range(5):
    q = rng.uniform(-np.pi, np.pi, 6)
    M = bot.inertia(q)
    rows.append("mass " + " ".join("%.17g" % x for x in np.concatenate([q, M.ravel()])))
    g = bot.gravload(q)
    rows.append("grav " + " ".join("%.17g" % x for x in np.concatenate([q, g])))
    T = bot.fkine(q).A
    rows.append("fk " + " ".join("%.17g" % x for x in np.concatenate([q, T[:3, :3].ravel(), T[:3, 3]])))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rtb_ref.txt")
with open(out, "w") as f:
    f.write("# GENERATED by gen_robot_ref.py (roboticstoolbox-python %s), gravity 0 0 -%g\n"
            % (rtb.__version__, G))
    f.write("\n".join(rows) + "\n")
print("wrote", out)
