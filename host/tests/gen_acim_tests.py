#!/usr/bin/env python3
"""Generate the induction motor tests from acim_motors.py:

  tests/acim_<motor>_id.test     idacim (id_acim) at standstill: rs, rr, lm,
                                 leakage and tau_r against the true motor; the
                                 rotor must not move.
  tests/acim_<motor>_speed.test  acvf with the parameters idacim found (the
                                 generator runs the autotune to get them):
                                 speed at half and near rated speed from no
                                 load to rated torque, belt travel reported to
                                 LinuxCNC against the true rotor travel, the
                                 stall flag on a blocked belt, recovery.

The drive is host/examples/conveyor_100w.conf (link acvf, sserial_acvf,
10 mm of belt per motor revolution) with the motor's values set over it;
the true motor goes to hv0.sim_* directly, so the controller only sees
what the autotune found. Loads are Coulomb friction (hv0.sim_f), like a belt.

Edit acim_motors.py, then run (needs ./stmbl_host):
  python3 tests/gen_acim_tests.py
"""

import math
import os
import re
import subprocess
import tempfile

from acim_motors import MOTORS, nameplate

HERE = os.path.dirname(os.path.abspath(__file__))
HOST = os.path.dirname(HERE)
CONF = "examples/conveyor_100w.conf"
MM_PER_RAD = 10.0 / (2 * math.pi)


def motor_lines(m):
    name, p_n, pp, rs, rr, lm, ll, j, u_n, f_n = m
    w_n, t_n, s_n, i_n = nameplate(m)
    return [
        "# true motor",
        "hv0.sim_type = 1",
        "hv0.sim_r = %g" % rs,
        "hv0.sim_rr = %g" % rr,
        "hv0.sim_lm = %g" % lm,
        "hv0.sim_l = %g" % ll,
        "hv0.sim_pp = %d" % pp,
        "hv0.sim_j = %g" % j,
        "hv0.sim_d = 0",
        "hv0.sim_f = %.4g" % (0.01 * t_n),
        "hv0.sim_udc = 325",
        "# drive: nameplate values",
        "conf0.polecount = %d" % pp,
        "conf0.max_ac_cur = %.3g" % (1.8 * i_n),
        "conf0.max_vel = %.1f" % (1.1 * 2 * math.pi * f_n / pp),
        "iit0.cur_boost = 1.8",
        "acvf0.u_n = %g" % u_n,
        "acvf0.vel_n = %.2f" % (2 * math.pi * f_n / pp),
        "acvf0.slip_n = %.4f" % s_n,
        "acvf0.torque_n = %.4f" % t_n,
    ]


def id_lines(m):
    w_n, t_n, s_n, i_n = nameplate(m)
    return motor_lines(m) + [
        "debug_level 1",
        "link id_acim",
        "relink",
        "start",
        "debug_level 0",
        "idacim0.test_cur = %.3g" % (0.7 * i_n),
        "fault0.cmd_error = 0",
        "fault0.en = 0",
        "run 0.5",
        "fault0.en = 1",
    ]


def identify(m):
    """Run idacim on the motor; return its results or None."""
    script = id_lines(m) + ["run 4", "idacim0.state"] + [
        "idacim0." + p for p in ("rs", "rr", "lm", "ll", "tau_r")]
    with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as f:
        f.write("\n".join(script) + "\n")
    try:
        out = subprocess.run(["./stmbl_host", "--drive", CONF, f.name], cwd=HOST,
                             stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                             universal_newlines=True, timeout=300).stdout
    finally:
        os.unlink(f.name)
    val = lambda p: float(re.findall(r"^idacim0\.%s = (\S+)$" % p, out, re.M)[-1])
    if val("state") != 5:
        return None
    return {p: val(p) for p in ("rs", "rr", "lm", "ll", "tau_r")}


def write_id_test(m):
    name, p_n, pp, rs, rr, lm, ll, j, u_n, f_n = m
    lr = lm + ll / 2
    text = ["# GENERATED by tests/gen_acim_tests.py -- edit acim_motors.py there.",
            "# idacim at standstill on %s (%d W, %d pole pairs): rs %g, rr %g," % (name, p_n, pp, rs, rr),
            "# lm %g, leakage %g, tau_r %.1f ms." % (lm, ll, lr / rr * 1e3),
            "@args --drive " + CONF] + id_lines(m) + [
            "@sample hv0.sim_vel 0.01 4",
            "idacim0.state", "idacim0.rs", "idacim0.rr", "idacim0.lm", "idacim0.ll",
            "idacim0.tau_r", "fault0.fault",
            "@expect idacim0.state == 5",
            "@expect idacim0.rs ~ %g 2%%" % rs,
            "@expect idacim0.rr ~ %g 5%%" % rr,
            "@expect idacim0.lm ~ %g 5%%" % lm,
            "@expect idacim0.ll ~ %g 10%%" % ll,
            "@expect idacim0.tau_r ~ %.5f 5%%" % (lr / rr),
            "@expect max|hv0.sim_vel| < 0.5",
            "@expect fault0.fault == 0"]
    with open(os.path.join(HERE, "%s_id.test" % name), "w") as fh:
        fh.write("\n".join(text) + "\n")


def write_speed_test(m, ident):
    name, p_n, pp, rs, rr, lm, ll, j, u_n, f_n = m
    w_n, t_n, s_n, i_n = nameplate(m)
    vel_n = 2 * math.pi * f_n / pp
    lines = ["# GENERATED by tests/gen_acim_tests.py -- edit acim_motors.py there.",
             "# acvf on %s with the autotune's parameters: speed vs load, travel" % name,
             "# reported to LinuxCNC, stall flag, recovery. Rated %.1f rad/s, %.3f Nm." % (w_n, t_n),
             "@args --drive " + CONF] + motor_lines(m) + [
             "# drive: autotune results",
             "conf0.r = %g" % ident["rs"],
             "acvf0.rr = %g" % ident["rr"],
             "acvf0.lm = %g" % ident["lm"],
             "acvf0.ll = %g" % ident["ll"],
             "# true belt travel [mm] for the comparison",
             "debug_level 1", "load scale", "scale0.rt_prio = 15",
             "scale0.in0 = hv0.sim_abs_pos", "scale0.scale = %.6f" % MM_PER_RAD,
             "relink", "start", "debug_level 0",
             "lcnc 0 0", "run 0.5", "lcnc 1 0", "run 0.5"]
    expects = ["@expect fault0.fault == 0", "@reject ^ERROR"]
    k = 0
    for frac in (0.5, 0.9):
        v = frac * vel_n
        lines.append("lcnc 1 %.4f" % (v * MM_PER_RAD))
        for load in (0.0, 0.5, 1.0):
            lines += ["hv0.sim_f = %.4g" % max(load * t_n, 0.01 * t_n), "run 3",
                      "hv0.sim_vel", "run 0.5", "hv0.sim_vel"]
            for _ in range(2):
                k += 1
                expects.append("@expect hv0.sim_vel[%d] ~ %.3f 1%%" % (k, v))
    # travel: stop, then compare the reported position with the true one
    lines += ["lcnc 1 0", "run 2", "sserial0.pos_fb", "scale0.out0"]
    expects.append("@expect sserial0.pos_fb ~ =scale0.out0 1%")
    # blocked belt, then cleared
    v = 0.5 * vel_n
    lines += ["lcnc 1 %.4f" % (v * MM_PER_RAD), "run 2",
              "hv0.sim_f = %.4g" % (4 * t_n), "run 6", "sserial0.in2", "fault0.fault",
              "hv0.sim_f = %.4g" % (0.3 * t_n), "run 4", "hv0.sim_vel", "sserial0.in2"]
    k += 1
    # from the end: the boot's link echo "OK sserial0.in2 <= ..." also counts
    expects += ["@expect sserial0.in2[-2] == 1",
                "@expect sserial0.in2[-1] == 0",
                "@expect hv0.sim_vel[%d] ~ %.3f 1%%" % (k, v)]
    with open(os.path.join(HERE, "%s_speed.test" % name), "w") as fh:
        fh.write("\n".join(lines + expects) + "\n")


def main():
    for m in MOTORS:
        write_id_test(m)
        ident = identify(m)
        if ident is None:
            print("  %-14s idacim failed: no speed test" % m[0])
            continue
        write_speed_test(m, ident)
        print("  %-14s rs %.3f rr %.3f lm %.4f ll %.4f tau_r %.4f" % (
            (m[0],) + tuple(ident[p] for p in ("rs", "rr", "lm", "ll", "tau_r"))))
    print("wrote tests for %d induction motors" % len(MOTORS))


if __name__ == "__main__":
    main()
