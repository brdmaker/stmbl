#!/usr/bin/env python3
"""Generate the linear axis soak test: examples/linear_axis.conf (ironless
linear motor, 60 mm electrical period, 1 m stroke with end stops, one
reference mark at -477 mm) in closed loop via the simulated LinuxCNC link,
in mm (linrev0.scale = 60).

The profile stays inside +-450 mm of the start (the end stops are at +-500):
  reference run (autophased until the mark at -477 mm, then absolute) and
  back, long trapezoids at vmax, 50 mm moves, reversals, sines at 1, 5 and
  20 Hz, 20 micro-steps of 10 um, unramped velocity steps, disable/enable
  (stays absolute), and a move back to the start.
Before the test is written, id_pid tunes the position/velocity loop on the
simulated axis (it moves about -155..+35 mm), with conf0.cur_bw = CUR_BW:
the default 1000 caps id_pid's vel_bw at 500, and an ironless motor (l / r
0.375 ms) takes a faster current loop. Check that on the real drive.

Pass: following error under FERROR mm in motion and REST mm at rest, no
fault, never at an end stop, current within max_ac_cur, commutation absolute
after the reference run.

usage: gen_linear_soak.py [--cycles N] [--out DIR] [--gains POS_BW VEL_BW VEL_D]
       (--gains skips id_pid)
"""

import argparse
import math
import os

import gen_soak_tests as gs

MM = 60.0 / (2 * math.pi)  # mm per rad
gs.MM_PER_RAD = MM         # Profile.tick sends mm/s to lcnc

VMAX = 1000.0 / MM         # 1 m/s
AMAX = 10000.0 / MM        # 10 m/s^2
STROKE = 450.0 / MM        # +-450 mm used
FERROR = 0.2               # mm, in motion
REST = 0.01                # mm, at rest (2 counts)
IMAX = 6.0
CUR_BW = 2000.0


def build(cycles):
    p = gs.Profile()
    p.section("reference")
    p.move(-485.0 / MM, 200.0 / MM, AMAX)
    p.hold(0.2)
    p.lines.append("enc_fb0.state")
    p.move(485.0 / MM, VMAX, AMAX)
    p.rest_check()
    for _ in range(cycles):
        p.section("trapezoid")
        for s in (1, -1, -1, 1):
            p.move(s * STROKE, VMAX, AMAX)
            p.rest_check(0.3)
        p.section("medium")
        for s in (1, -1, 1, -1):
            p.move(s * 50.0 / MM, 0.5 * VMAX, 0.5 * AMAX)
            p.hold(0.2)
        p.rest_check()
        p.section("reversals")
        for k in range(10):
            p.ramp_to((1 if k % 2 == 0 else -1) * 0.3 * VMAX, AMAX)
        p.ramp_to(0.0, AMAX)
        p.rest_check()
        p.section("sines")
        for f in (1.0, 5.0, 20.0):
            w = 2 * math.pi * f
            amp = min(0.5 * VMAX / w, 0.8 * AMAX / w ** 2, 50.0 / MM)
            p.sine(f, amp, max(2, int(f)))
        p.rest_check()
        p.section("micro")  # 10 um, alternating
        for k in range(20):
            p.move((1 if k % 2 == 0 else -1) * 0.01 / MM, VMAX, AMAX)
            p.hold(0.05)
        p.rest_check()
        p.section("vsteps")  # no ramp, 20 mm/s
        dv = 20.0 / MM
        for v in (dv, 0.0, -dv, 0.0):
            p.tick(v)
            p.cruise(0.3)
        p.rest_check()
        p.section("enable")
        p.lines += ["lcnc 0 0", "run 0.3", "fault0.state", "lcnc 1 0", "run 1.5",
                    "enc_fb0.state"]
        p.move(5.0 / MM, 0.5 * VMAX, 0.5 * AMAX)
        p.move(-p.pos, VMAX, AMAX)  # p.pos keeps the tick-rounding rest
        p.rest_check()
    return p


ARGS = ("--drive", "examples/linear_axis.conf", "--sim", "examples/linear_axis_sim.txt")

TEMPLATE = """\
# GENERATED by tests/gen_linear_soak.py -- edit the profile there.
# Soak: ironless linear axis (examples/linear_axis.conf) in closed loop via
# the simulated LinuxCNC link, {cycles} cycle(s), {t:.0f} s simulated.
# 1 m/s, 10 m/s^2, within +-450 mm of a 1 m stroke.
@args --drive examples/linear_axis.conf --sim examples/linear_axis_sim.txt
@timeout {timeout}
{gains}debug_level 0
lcnc 0 0
run 0.5
lcnc 1 0
run 1.5
{body}
fault0.state
sserial0.error
hv0.sim_stop_hits
hv0.sim_abs_pos
@expect max fault0.fault < 0.5
@expect fault0.state[-1] == 1
@expect sserial0.error == 0
@expect min enc_fb0.state >= 3
@expect hv0.sim_stop_hits == 0
@expect hv0.sim_abs_pos ~ {end:.6f} {rest:.5f}
@expect max|pid0.pos_error| < {ferror:.5f}
@expect max|fault0.pos_error| < {rest:.5f}
@expect max|hv0.sim_vel| < {vlim:.1f}
@expect max|hv0.iq_fb| < {ilim:.3g}
@reject ^ERROR
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cycles", type=int, default=1)
    ap.add_argument("--gains", type=float, nargs=3, metavar=("POS_BW", "VEL_BW", "VEL_D"))
    ap.add_argument("--out", default=os.path.join(gs.HOST_DIR, "gen", "soak"))
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    g = args.gains
    if g is None:
        g = gs.tune(["conf0.cur_bw = %g" % CUR_BW], drive_args=ARGS)
    if g is None:
        gains = "@fail id_pid did not finish on the linear axis\n"
    else:
        gains = ("conf0.cur_bw = %g\n# id_pid result\nconf0.pos_bw = %.4f\n"
                 "conf0.vel_bw = %.4f\nconf0.vel_d = %.4f\n" % ((CUR_BW,) + tuple(g)))
        print("  linear_axis     pos_bw %.1f vel_bw %.0f vel_d %.2f" % tuple(g))
    p = build(args.cycles)
    text = TEMPLATE.format(cycles=args.cycles, t=p.t + 2.0 * args.cycles + 2.0,
                           timeout=120 * args.cycles, end=p.pos, gains=gains, body="\n".join(p.lines),
                           ferror=FERROR / MM, rest=REST / MM, vlim=1.2 * VMAX,
                           ilim=1.05 * IMAX)
    out = os.path.join(args.out, "soak_linear_axis.test")
    with open(out, "w") as fh:
        fh.write(text)
    print("wrote %s" % out)


if __name__ == "__main__":
    main()
