#!/usr/bin/env python3
"""Generate tests/motor_*.test: rlpsij autotune on 20 motors.

Motors come from conf/*.txt (r, l, polecount, j, max_ac_cur). Where a config
has no conf0.psi, psi = max_force / (1.5 * polecount * max_ac_cur), i.e. the
torque constant at peak current. Each test runs the simulated drive with the
motor set through conf0 (host/sim_board.txt links hv0.sim_* to conf0), so
rlpsij, which does not read conf0, identifies it blind.

Edit the table, then run:  python3 tests/gen_motor_tests.py
"""

import os

# name, r [ohm], l [H], psi [Wb], polecount, j [kg m^2], max_ac_cur [A]
MOTORS = [
    ("ecma_c30604fs",  2.1517, 0.022957, 0.047433, 5, 0.000044,   10),
    ("e240",           1.4,    0.0013,   0.2,      1, 0.0000268,  13),
    ("rx60_456",       10,     0.002,    0.1961,   1, 0.00001,    17),
    ("fanuc_a06b",     0.6,    0.01,     0.1852,   4, 0.00035,    18),
    ("fanuc_b05_6000", 1,      0.005,    0.1852,   4, 0.000025,   18),
    ("festo",          9.6,    0.01,     0.05,     4, 0.000026,   10),
    ("manutec_r15_1",  0.4,    0.002,    0.08,     3, 0.00035,    5),
    ("mitsu",          1.2,    0.005,    0.1333,   2, 0.00005,    10),
    ("move",           2,      0.007,    0.0667,   5, 0.00003,    3),
    ("p50b",           0.4,    0.01,     0.38,     2, 0.0001,     5),
    ("r2aa04003f",     12,     0.00066,  0.0267,   5, 0.00000247, 2),
    ("r2aa06020f",     2.7,    0.0007,   0.0524,   5, 0.0000219,  5.6),
    ("rexroth",        3.75,   0.008,    0.1111,   3, 0.000013,   6),
    ("rx60_123",       0.4,    0.002,    0.098,    2, 0.0001,     17),
    ("sda_b",          5,      0.01,     0.1,      5, 0.00005,    4),
    ("sgmph_01a1",     5,      0.01,     0.1667,   3, 0.0000015,  4),
    ("sgmph_08aa",     5,      0.01,     0.1333,   3, 0.0001,     10),
    ("sm060",          1.6,    0.008,    0.0844,   5, 0.00007,    9),
    ("sr60_2",         25.5,   0.001,    0.0467,   4, 0.000015,   2.5),
    ("weiler_x",       0.4,    0.01,     0.3333,   2, 0.00007,    10),
]

# Tolerances on the identified values.
TOL_R, TOL_PSI, TOL_J, TOL_F, TOL_L = "3%", "5%", "10%", "15%", "10%"
# l is only checked when the electrical time constant spans a few rt
# periods (0.2 ms); below that it is unobservable at 5 kHz.
L_MIN_TAU = 0.0005

TEMPLATE = """\
# GENERATED by tests/gen_motor_tests.py -- edit the table there.
# rlpsij autotune on motor {name}: r {r}, l {l}, psi {psi},
# polecount {pp}, j {j}, test_cur {cur} (30% of max_ac_cur {imax}).
@args --drive ../hwtest/burnin/ECMA-C30604FS/stmbl.conf
conf0.r = {r}
conf0.l = {l}
conf0.psi = {psi}
conf0.polecount = {pp}
conf0.j = {j}
conf0.f = {f}
conf0.d = 0.0001
conf0.max_ac_cur = {imax}
@include tests/inc/rlpsij_hv0.txt
rlpsij0.test_cur = {cur}
rlpsij0.abs_pos_fb = hv0.sim_pos
# j and l x 1e6, so the 6-decimal console keeps their digits
load scale
load scale
scale0.rt_prio = 15
scale0.scale = 1000000
scale0.in0 = rlpsij0.j
scale1.rt_prio = 15
scale1.scale = 1000000
scale1.in0 = rlpsij0.l
relink
start
debug_level 0
fault0.cmd_error = 0
rlpsij0.en = 1
@sample hv0.sim_vel 0.002 18
rlpsij0.state
rlpsij0.r
rlpsij0.psi
rlpsij0.polecount
rlpsij0.friction
rlpsij0.damping
rlpsij0.load
scale0.out0
scale1.out0
@expect rlpsij0.state == 6
@expect rlpsij0.r ~ {r} {tol_r}
@expect rlpsij0.polecount == {pp}
@expect rlpsij0.psi ~ {psi} {tol_psi}
@expect scale0.out0 ~ {j_u} {tol_j}
@expect rlpsij0.friction ~ {f} {tol_f}
{l_check}@expect max|hv0.sim_vel| < 80
"""


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    for name, r, l, psi, pp, j, imax in MOTORS:
        cur = round(0.3 * imax, 2)
        # Coulomb friction ~2% of peak torque.
        f = round(0.02 * 1.5 * pp * psi * imax, 4)
        text = TEMPLATE.format(name=name, r=r, l=l, psi=psi, pp=pp, j=j, f=f,
                               j_u=round(j * 1e6, 4), tol_f=TOL_F,
                               l_check=("@expect scale1.out0 ~ %g %s\n" % (round(l * 1e6, 4), TOL_L)
                                        if l / r >= L_MIN_TAU else
                                        "# l not checked: l / r = %.0f us < %.0f us\n"
                                        % (l / r * 1e6, L_MIN_TAU * 1e6)),
                               imax=imax, cur=cur, tol_r=TOL_R,
                               tol_psi=TOL_PSI, tol_j=TOL_J)
        with open(os.path.join(here, "motor_%s.test" % name), "w") as fh:
            fh.write(text)
    print("wrote %d motor tests" % len(MOTORS))


if __name__ == "__main__":
    main()
