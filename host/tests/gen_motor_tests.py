#!/usr/bin/env python3
"""Generate tests/motor_*.test: rlpsij autotune on every motor in motors.py.

Motors are in motors.py. Each test runs the simulated drive with the
motor set through conf0 (host/sim_board.txt links hv0.sim_* to conf0), so
rlpsij, which does not read conf0, identifies it blind.

Edit the table, then run:  python3 tests/gen_motor_tests.py
"""

import os

from motors import MOTORS

# Tolerances on the identified values.
TOL_R, TOL_PSI, TOL_J, TOL_F, TOL_L = "3%", "5%", "10%", "15%", "10%"
# l is only checked when the electrical time constant spans a few rt
# periods (0.2 ms); below that it is unobservable at 5 kHz.
L_MIN_TAU = 0.0005

# Known failures, marked @todo (they show, but don't fail the run).
KNOWN = {
}

TEMPLATE = """\
# GENERATED by tests/gen_motor_tests.py -- edit the table there.
# rlpsij autotune on motor {name}: r {r}, l {l}, psi {psi},
# polecount {pp}, j {j}, test_cur {cur} (30% of max_ac_cur {imax}).
@args --drive ../hwtest/burnin/ECMA-C30604FS/stmbl.conf
conf0.r = {r}
conf0.l = {l}
conf0.psi = {psi}
conf0.polecount = {pp}
conf0.j = {j}
conf0.f = {f}
conf0.d = {d}
conf0.max_ac_cur = {imax}
@include tests/inc/rlpsij_hv0.txt
rlpsij0.test_cur = {cur}
rlpsij0.abs_pos_fb = hv0.sim_pos
# j and l x 1e6, so the 6-decimal console keeps their digits
load scale
load scale
scale0.rt_prio = 15
scale0.scale = 1000000
scale0.in0 = rlpsij0.j
scale1.rt_prio = 15
scale1.scale = 1000000
scale1.in0 = rlpsij0.l
relink
start
debug_level 0
fault0.cmd_error = 0
rlpsij0.en = 1
@sample hv0.sim_vel 0.002 {t_run}
rlpsij0.state
rlpsij0.r
rlpsij0.psi
rlpsij0.polecount
rlpsij0.friction
rlpsij0.damping
rlpsij0.load
scale0.out0
scale1.out0
@expect rlpsij0.state == 6
@expect rlpsij0.r ~ {r} {tol_r}
@expect rlpsij0.polecount == {pp}
@expect rlpsij0.psi ~ {psi} {tol_psi}
@expect scale0.out0 ~ {j_u} {tol_j}
@expect rlpsij0.friction ~ {f} {tol_f}
{l_check}@expect max|hv0.sim_vel| < 80
{todo}"""


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    for name, r, l, psi, pp, j, imax in MOTORS:
        cur = round(0.3 * imax, 2)
        # Coulomb friction 2% of peak torque; viscous damping scaled like the
        # bench motor's (1e-4 Nm*s/rad at 3.56 Nm peak).
        t_peak = 1.5 * pp * psi * imax
        f = round(0.02 * t_peak, 4)
        d = float("%.3g" % (2.8e-5 * t_peak))
        text = TEMPLATE.format(name=name, r=r, l=l, psi=psi, pp=pp, j=j, f=f, d=d,
                               j_u=round(j * 1e6, 4), tol_f=TOL_F,
                               # state 3 turns the field 1 electrical rev/s
                               t_run=14 + pp,
                               l_check=("@expect scale1.out0 ~ %g %s\n" % (round(l * 1e6, 4), TOL_L)
                                        if l / r >= L_MIN_TAU else
                                        "# l not checked: l / r = %.0f us < %.0f us\n"
                                        % (l / r * 1e6, L_MIN_TAU * 1e6)),
                               imax=imax, cur=cur, tol_r=TOL_R,
                               tol_psi=TOL_PSI, tol_j=TOL_J,
                               todo="@todo %s\n" % KNOWN[name] if name in KNOWN else "")
        with open(os.path.join(here, "motor_%s.test" % name), "w") as fh:
            fh.write(text)
    print("wrote %d motor tests" % len(MOTORS))


if __name__ == "__main__":
    main()
